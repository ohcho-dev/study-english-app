#!/bin/bash

# 프로젝트 루트 경로 설정
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
NGROK_CONFIG="$PROJECT_ROOT/ngrok.yml"
ADMIN_ENV_FILE="$PROJECT_ROOT/apps/admin/.env.local"

# Add Homebrew to PATH for M1/M2 Macs
export PATH="/opt/homebrew/bin:$PATH"

echo "🌐 Starting Dual Ngrok Tunnels..."

# 1. Start Ngrok in background
# nohup을 사용하여 터미널이 닫혀도 유지되게 하거나, 단순히 백그라운드 실행
# 기본 설정 파일(인증 토큰 포함)도 함께 로드합니다.
DEFAULT_CONFIG="$HOME/Library/Application Support/ngrok/ngrok.yml"

if [ -f "$DEFAULT_CONFIG" ]; then
    echo "Starting ngrok with default config..."
    ngrok start --all --config="$DEFAULT_CONFIG" --config="$NGROK_CONFIG" > ngrok.log 2>&1 &
else
    echo "⚠️  Default ngrok config not found at $DEFAULT_CONFIG. Authentication might fail."
    ngrok start --all --config="$NGROK_CONFIG" > ngrok.log 2>&1 &
fi
NGROK_PID=$!

echo "⏳ Waiting for Ngrok to initialize (5s)..."
sleep 5

# 2. Fetch Tunnels Info
# ngrok 로컬 API를 통해 터널 정보 조회
TUNNELS_JSON=$(curl -s http://127.0.0.1:4040/api/tunnels)

if [ -z "$TUNNELS_JSON" ]; then
    echo "❌ Failed to connect to Ngrok API. Is ngrok running?"
    kill $NGROK_PID 2>/dev/null
    exit 1
fi

# 3. Extract URLs using jq
# study-english-server 터널의 public_url 추출
SERVER_URL=$(echo "$TUNNELS_JSON" | jq -r '.tunnels[] | select(.name=="study-english-server") | .public_url')
ADMIN_URL=$(echo "$TUNNELS_JSON" | jq -r '.tunnels[] | select(.name=="study-english-admin") | .public_url')

if [ -z "$SERVER_URL" ] || [ "$SERVER_URL" == "null" ]; then
    echo "❌ Failed to find Server tunnel URL."
    kill $NGROK_PID 2>/dev/null
    exit 1
fi

echo "✅ Tunnels Established!"
echo "   - Server Public URL: $SERVER_URL"
echo "   - Admin Public URL:  $ADMIN_URL"

# 4. Update Admin Environment
echo "📝 Updating Admin Configuration..."
echo "# Generated by scripts/share-network.sh" > "$ADMIN_ENV_FILE"
echo "NEXT_PUBLIC_API_URL=$SERVER_URL" >> "$ADMIN_ENV_FILE"

echo "✅ apps/admin/.env.local updated."
echo "---------------------------------------------------"
echo "🚀 Next Steps:"
echo "1. Run './scripts/start-server-prod.sh' in a new terminal."
echo "2. Run './scripts/start-admin-prod-share.sh' in another terminal."
echo "   (This will rebuild the admin app with the new API URL)"
echo "---------------------------------------------------"
echo "Press Ctrl+C to stop Ngrok."

# Wait for user interrupt
wait $NGROK_PID
