"""Narrative Sync v0.2 Pipeline Data Contract schemas.

This module defines the JSON contract schemas for the Expert Pipeline:
Evaluator → Planner → Conductor.
All inter-module communication uses schema_version-tagged JSON.
"""

from datetime import datetime
from typing import Optional
from uuid import UUID

from pydantic import BaseModel, Field


SCHEMA_VERSION = "0.2.0"


# ============================================================================
# Common Meta
# ============================================================================


class CommonMeta(BaseModel):
    """Common metadata included in all pipeline messages."""

    schema_version: str = Field(default=SCHEMA_VERSION, description="Data contract version")
    trace_id: str = Field(description="UUID tracing the full pipeline execution")
    session_id: str = Field(description="Conversation session ID")
    turn_id: str = Field(description="Turn identifier within the session")
    timestamp: str = Field(description="ISO 8601 timestamp")


# ============================================================================
# Evaluator Schemas
# ============================================================================


class SlotScore(BaseModel):
    """Score for a single narrative slot (A/B/C)."""

    score: int = Field(ge=0, le=10, description="Slot score 0-10")
    is_missing: bool = Field(default=False, description="Whether the slot was missing")
    evidence: str = Field(default="", description="Evidence text from user utterance")


class AggregateScores(BaseModel):
    """Aggregated scores from the Evaluator."""

    slot_avg: float = Field(ge=0, le=10, description="Average of slot scores")
    imitation_score: int = Field(ge=0, le=10, description="How well user imitated the pattern")
    complexity_score: int = Field(ge=0, le=10, description="Language complexity")
    overall_score: int = Field(ge=0, le=100, description="Overall score 0-100")


class DetectedElements(BaseModel):
    """Elements detected in user utterance."""

    anchors: list[str] = Field(default_factory=list, description="Detected anchor phrases")
    connectors: list[str] = Field(default_factory=list, description="Detected connectors")
    used_key_phrases: list[str] = Field(default_factory=list, description="Key phrases used")


class FluencyMetrics(BaseModel):
    """Fluency-related measurements."""

    pause_count: int = Field(default=0, ge=0, description="Number of pauses detected")
    words_per_minute: float = Field(default=0.0, ge=0, description="Speaking speed")


class Diagnosis(BaseModel):
    """Evaluator's diagnosis of the user's performance."""

    primary_issue: str = Field(
        default="NONE",
        description="Main issue: MISSING_SLOT_A, MISSING_SLOT_B, MISSING_SLOT_C, LOW_IMITATION, NONE",
    )
    secondary_issues: list[str] = Field(default_factory=list, description="Additional issues")
    recommended_action: str = Field(
        default="CONTINUE",
        description="Hint for Planner: TRIGGER_HELPER, ADD_MODELING, DENSITY_UP, CONTINUE",
    )


class EvaluatorOutput(BaseModel):
    """Full output from the Evaluator module."""

    schema_version: str = Field(default=SCHEMA_VERSION)
    trace_id: str = Field(default="")
    session_id: str = Field(default="")
    turn_id: str = Field(default="")
    narrative_scores: dict[str, SlotScore] = Field(
        default_factory=lambda: {
            "slot_a": SlotScore(score=0, is_missing=True),
            "slot_b": SlotScore(score=0, is_missing=True),
            "slot_c": SlotScore(score=0, is_missing=True),
        },
        description="Scores for each narrative slot",
    )
    aggregate: AggregateScores = Field(default_factory=lambda: AggregateScores(
        slot_avg=0, imitation_score=0, complexity_score=0, overall_score=0
    ))
    detected: DetectedElements = Field(default_factory=DetectedElements)
    fluency: FluencyMetrics = Field(default_factory=FluencyMetrics)
    diagnosis: Diagnosis = Field(default_factory=Diagnosis)


# ============================================================================
# Planner Schemas
# ============================================================================


class DecisionConstraints(BaseModel):
    """Constraints for the next turn generated by Planner."""

    target_pattern: str = Field(default="ABC", description="Target narrative pattern")
    must_include: list[str] = Field(default_factory=list, description="Must-include elements")
    banned: list[str] = Field(default_factory=list, description="Banned elements")


class Decision(BaseModel):
    """Planner's strategic decision."""

    path: str = Field(description="LEVEL_DOWN | LEVEL_HOLD | LEVEL_UP | LEVEL_JUMP")
    action_code: str = Field(description="LEVEL_ADJUST")
    reason: list[str] = Field(default_factory=list, description="Reasons for the decision")
    next_constraints: DecisionConstraints = Field(default_factory=DecisionConstraints)


class PersonaPlan(BaseModel):
    """Plan for which personas should speak and how."""

    speakers: list[str] = Field(default_factory=list, description="Persona names in order")
    order: list[str] = Field(default_factory=list, description="Speaking order")
    tone: str = Field(default="neutral", description="Tone for the response")
    language: str = Field(default="en-US", description="Language code")
    current_level: int = Field(default=1, ge=1, le=10, description="Current difficulty level")


class PlannerOutput(BaseModel):
    """Full output from the Planner module."""

    schema_version: str = Field(default=SCHEMA_VERSION)
    trace_id: str = Field(default="")
    turn_id: str = Field(default="")
    decision: Decision = Field(description="Strategic decision")
    persona_plan: PersonaPlan = Field(default_factory=PersonaPlan)


# ============================================================================
# Conductor Schemas
# ============================================================================


class EnergyFlowComparison(BaseModel):
    """A single row in the energy flow comparison table."""

    korean: str = Field(description="Korean situation/expression")
    english: str = Field(description="English expression with control verb")
    direction: str = Field(description="Energy direction description in Korean")


class EnergyFlowOutput(BaseModel):
    """Energy flow visualization data for a control verb."""

    verb: str = Field(description="Control verb (e.g., HAVE, GET, PUT)")
    core_energy: str = Field(description="Core energy description in Korean")
    comparisons: list[EnergyFlowComparison] = Field(
        default_factory=list,
        description="Comparison rows showing different energy directions",
    )


class ConductorScript(BaseModel):
    """Generated script for a single persona."""

    speaker_name: str = Field(description="Persona name")
    text: str = Field(description="Generated text to speak")
    instruction: str = Field(default="", description="Internal instruction for this speaker")
    language: str = Field(default="en-US", description="Language of the text")


class ConductorOutput(BaseModel):
    """Full output from the Conductor module."""

    schema_version: str = Field(default=SCHEMA_VERSION)
    trace_id: str = Field(default="")
    turn_id: str = Field(default="")
    scripts: list[ConductorScript] = Field(default_factory=list, description="Generated scripts")
    return_to_user_after: bool = Field(default=False, description="Whether to return to user after all scripts")
    user_emotion: str = Field(default="neutral", description="Detected or inferred user emotion")
    feedback_text: str = Field(default="", description="Moderator feedback text for the user")
    feedback_instruction: str = Field(default="", description="Delivery instruction for moderator, passed directly to moderator LLM")
    level_instruction: str = Field(default="", description="Level instruction for AI participants")
    corrections: list[str] = Field(default_factory=list, description="Grammar/expression corrections")
    better_expressions: list[str] = Field(default_factory=list, description="Suggested better expressions")
    energy_flow: dict | None = Field(default=None, description="Energy flow comparison data for UI visualization")


# ============================================================================
# Pipeline Log Schemas (for API responses)
# ============================================================================


class PipelineLogResponse(BaseModel):
    """Schema for pipeline log API response."""

    id: UUID
    trace_id: str
    session_id: UUID
    turn_index: int
    module_name: str
    schema_version: str
    input_json: dict | None = None
    output_json: dict | None = None
    duration_ms: float | None = None
    model_name: str | None = None
    error_message: str | None = None
    created_at: datetime

    class Config:
        """Pydantic config."""

        from_attributes = True


class PipelineLogListResponse(BaseModel):
    """Response for listing pipeline logs."""

    items: list[PipelineLogResponse]
    total: int


# ============================================================================
# Prompt Management Schemas
# ============================================================================


class TemplatePromptsResponse(BaseModel):
    """Response for template prompts (all 4 types)."""

    pipeline_mode: str = Field(default="basic", description="basic or v0.2")
    basic_prompt: str | None = Field(None, description="Director system prompt (basic mode)")
    evaluator_prompt: str | None = Field(None, description="Evaluator custom prompt")
    planner_prompt: str | None = Field(None, description="Planner custom prompt")
    conductor_prompt: str | None = Field(None, description="Conductor custom prompt")


class TemplatePromptsUpdate(BaseModel):
    """Request to update template prompts."""

    pipeline_mode: str | None = Field(None, description="basic or v0.2")
    basic_prompt: str | None = Field(None, description="Director system prompt")
    evaluator_prompt: str | None = Field(None, description="Evaluator custom prompt")
    planner_prompt: str | None = Field(None, description="Planner custom prompt")
    conductor_prompt: str | None = Field(None, description="Conductor custom prompt")
